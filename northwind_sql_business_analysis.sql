/* Average order value per customer */
SELECT o.customer_id,concat(first_name,' ',last_name) AS customer_name,
AVG(order_totals.order_total) AS avg_order_value
FROM orders o
JOIN (
    SELECT order_id, SUM(quantity * unit_price) AS order_total
    FROM order_details
    GROUP BY order_id
) AS order_totals ON o.id = order_totals.order_id
JOIN customers ON o.customer_id = customers.id
GROUP BY o.customer_id
ORDER BY o.customer_id;

