/* For each order, show customer name, employee who handled it, 
and shipping company */
SELECT 
    concat(c.first_name,' ', c.last_name) AS customer_name,
    concat(e.first_name,' ', e.last_name) AS employee_name,
    s.company AS shipping_company
FROM orders o
JOIN customers c ON o.customer_id = c.id
JOIN employees e ON o.employee_id = e.id
JOIN shippers s ON o.shipper_id = s.id;

/* List the top 10 products by total revenue, including category */
SELECT products.id, product_name, SUM(quantity * unit_price) AS total_revenue, category
FROM products
JOIN order_details ON products.id = order_details.product_id
GROUP BY products.id, product_name, category
ORDER BY total_revenue DESC
LIMIT 10;

/* Find all customers who have never placed an order */ 
SELECT customers.id, customers.first_name, customers.last_name
FROM customers
LEFT JOIN orders ON customers.id = orders.customer_id
WHERE orders.id IS NULL;

/*List employees and the total revenue they've generated through their orders*/
SELECT employees.id,concat(first_name,' ',last_name) AS employee_name,
SUM(quantity * unit_price) as revenue_generated
FROM employees
JOIN orders ON employees.id = orders.employee_id
JOIN order_details ON orders.id = order_details.order_id
GROUP BY id,employee_name
ORDER BY id;

/* Rank customers by total spend */
SELECT customers.id,concat(first_name,' ',last_name) AS customer_name,
SUM(quantity * unit_price) as total_spend,
RANK() OVER (ORDER BY SUM(quantity * unit_price) DESC) AS spend_rank
FROM customers
JOIN  orders ON customers.id = orders.customer_id
JOIN order_details ON orders.id = order_details.order_id
GROUP BY customers.id,customer_name;

/* Running total of spend per customer over time */
SELECT customers.id,orders.id,order_date,
	SUM(quantity * unit_price) AS order_total,
	SUM(SUM(quantity * unit_price))
OVER(PARTITION BY customers.id ORDER BY order_date)
AS running_total
FROM customers
JOIN orders ON customers.id = orders.customer_id
JOIN order_details ON orders.id = order_details.order_id
GROUP BY customers.id,orders.id,order_date
ORDER BY customers.id,order_date;

