/* Month-over-month revenue change */
WITH monthly AS (
SELECT DATE_FORMAT(order_date,'%Y-%m') AS month,
		SUM(quantity * unit_price) AS revenue
FROM orders
JOIN order_details ON orders.id = order_details.order_id
GROUP BY DATE_FORMAT (order_date,'%Y-%m')
)
SELECT month, revenue,
	LAG(revenue) OVER (ORDER BY month) AS prev_month_revenue,
    revenue - LAG(revenue) OVER (ORDER BY month) AS changes
FROM monthly
ORDER BY month;

/* Top 3 best-selling products per category */
WITH product_sales AS (
	SELECT products.id,product_name,category,
		SUM(quantity * unit_price) AS revenue
	FROM products
    JOIN order_details ON products.id = order_details.product_id
    GROUP BY products.id, product_name, products.category
),
ranked AS (
	SELECT *,RANK() OVER (PARTITION BY category ORDER BY revenue DESC) AS rnk 
    FROM product_sales
)
SELECT * FROM ranked WHERE rnk <= 3;

/* Customers spending above the average */
WITH customer_spend AS (
    SELECT c.id, c.first_name, c.last_name,
           SUM(od.quantity * od.unit_price) AS total_spend
    FROM customers c
    JOIN orders o ON c.id = o.customer_id
    JOIN order_details od ON o.id = od.order_id
    GROUP BY c.id, c.first_name, c.last_name
)
SELECT * FROM customer_spend
WHERE total_spend > (SELECT AVG(total_spend) FROM customer_spend);